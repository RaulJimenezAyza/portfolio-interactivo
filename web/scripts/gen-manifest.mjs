/* Lists whatever is sitting in public/models and writes it to a generated
 * module the app imports.
 *
 * The alternative was a runtime HEAD request per model to find out whether a
 * file is there, which costs a round trip each and, on GitHub Pages, comes
 * back as a 200 with an HTML 404 page rather than an honest 404. A static site
 * knows its own contents at build time; asking the network is asking the wrong
 * source. Drop a .glb in the folder, rebuild, and the registry picks it up
 * with no code edit — which is the whole point of the folder.
 */
import { readdirSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const modelsDir = join(here, "..", "public", "models");
const outFile = join(here, "..", "src", "models", "manifest.generated.ts");

if (!existsSync(modelsDir)) mkdirSync(modelsDir, { recursive: true });

const files = readdirSync(modelsDir)
  .filter(f => /\.(glb|gltf)$/i.test(f))
  .sort();

writeFileSync(outFile, `/* GENERATED by scripts/gen-manifest.mjs — do not edit.
 * Rerun with \`npm run models\` (also runs on predev and prebuild). */
export const MODEL_FILES: readonly string[] = ${JSON.stringify(files, null, 2)};
`, "utf8");

console.log(`models: ${files.length ? files.join(", ") : "(none — all procedural)"}`);
