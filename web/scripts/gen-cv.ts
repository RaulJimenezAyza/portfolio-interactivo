/* Renders the CV as static HTML, from the same tables the island reads.
 *
 * The whole résumé — every project, skill and job — lives in four arrays in
 * world.js and reaches a visitor through a WebGL canvas and a button. That is
 * the point of the thing, but it means anything that is not a browser gets a
 * <title> and an empty page: a search engine indexing a portfolio with no
 * portfolio in it, and a screen reader arriving before boot() has run.
 *
 * So the same data is rendered a second way, as a plain document, and put in
 * the page at build time. It is visually hidden and not aria-hidden — the
 * island is the experience, this is the fallback underneath it, and both say
 * exactly the same thing because both come from the same source. Rendered
 * here rather than by hand for that reason: a second copy of a CV is a copy
 * that goes stale the first time a job changes.
 *
 *   npx tsx scripts/gen-cv.ts        (runs on predev and prebuild)
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { installDomStub } from "./dom-stub";

const here = dirname(fileURLToPath(import.meta.url));
const outFile = join(here, "..", "src", "content", "cv.generated.ts");

/** Spanish, to match `<html lang="es">`. The toggle in the game is for the
 *  visitor; a crawler is handed one language and it should be the one the
 *  document declares. */
const LANG = "es";

type Localised = string | Record<string, string>;
const L = (v: Localised) =>
  v && typeof v === "object" && !Array.isArray(v) ? (v as any)[LANG] ?? (v as any).es : (v as string);

/* Everything below is interpolated into HTML, and all of it comes from
   world.js rather than from a user — but the escape stays, because the day
   someone puts an ampersand in a job title is not the day to find out. */
const esc = (s: string) =>
  String(s).replace(/[&<>"]/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]!));

async function main() {
  installDomStub();
  const mod: any = await import("../src/game/world.js");
  const { I18N, PROJECTS, SKILLS, TIMELINE } = mod.__content ?? {};
  if (!I18N || !PROJECTS || !SKILLS || !TIMELINE)
    throw new Error("world.js did not export __content — see the note at the bottom of that file");

  const t = I18N[LANG];

  const head = `<h1>Raúl Jiménez Ayza</h1>
<p>${esc(t.role)}. Lliçà d'Amunt, Barcelona.</p>
<p>${esc(t.aboutP1)}</p>
<p>${esc(t.aboutP2)}</p>`;

  const work = `<h2>${esc(t.workTitle)}</h2>
<ul>${PROJECTS.map((p: any) => `
  <li>
    <h3>${esc(L(p.title))}</h3>
    <p>${esc(L(p.kind))} — ${esc(L(p.blurb))}</p>
    <p>${esc(L(p.body))}</p>
    <p>${p.tags.map((g: Localised) => esc(L(g))).join(", ")}</p>
    ${p.web ? `<p><a href="${esc(p.web)}" rel="noopener">${esc(p.web)}</a></p>` : ""}
    ${p.link ? `<p><a href="${esc(p.link)}" rel="noopener">${esc(p.link)}</a></p>` : ""}
  </li>`).join("")}
</ul>`;

  const skills = `<h2>${esc(t.skillsTitle)}</h2>
<ul>${SKILLS.map((s: any) => `
  <li>${esc(L(s.label))}: ${s.items.map((i: Localised) => esc(L(i))).join(", ")}</li>`).join("")}
</ul>`;

  const path = `<h2>${esc(t.pathTitle)}</h2>
<ul>${TIMELINE.map((n: any) => `
  <li>
    <h3>${esc(L(n.role))} — ${esc(L(n.place))}</h3>
    <p>${esc(L(n.when))}</p>
    <p>${esc(L(n.detail))}</p>
  </li>`).join("")}
</ul>`;

  const contact = `<h2>${esc(t.contactTitle)}</h2>
<p>${esc(t.contactBody)}</p>
<ul>
  <li><a href="mailto:rauljayza@gmail.com">rauljayza@gmail.com</a></li>
  <li><a href="https://github.com/RaulJimenezAyza" rel="noopener">github.com/RaulJimenezAyza</a></li>
  <li><a href="https://www.linkedin.com/in/raul-jimenez-ayza/" rel="noopener">linkedin.com/in/raul-jimenez-ayza</a></li>
</ul>`;

  const html = [head, path, work, skills, contact].join("\n\n");

  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, `/* GENERATED by scripts/gen-cv.ts — do not edit.
 * Rerun with \`npm run cv\` (also runs on predev and prebuild).
 * The source is the I18N, PROJECTS, SKILLS and TIMELINE tables in
 * src/game/world.js; see the note at the bottom of that file. */
export const CV_HTML = ${JSON.stringify(html)};
`, "utf8");

  const words = html.replace(/<[^>]+>/g, " ").split(/\s+/).filter(Boolean).length;
  console.log(`cv:     src/content/cv.generated.ts — ${words} words, ${TIMELINE.length} roles, ${PROJECTS.length} projects`);
}

main().catch(err => {
  console.error(`cv:     FAILED — ${err?.message ?? err}`);
  process.exit(1);
});
